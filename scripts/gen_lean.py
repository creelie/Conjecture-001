"""Writes lean/H1/Counterexample.lean.

K is the 14-element semidistributive lattice given by its covering pairs below. L is the sublattice of
K x K generated by the diagonal {(x, x)} and the single pair (1, 3); it has 26 elements. The script
computes L, its join and meet tables, and, for every element c of L off the diagonal, a chain of joins
and meets that generates all of L from the diagonal and c. That chain is the Lean proof that the
diagonal is a maximal proper sublattice of L. Run from the repository root: python3 scripts/gen_lean.py
"""
import os

K_COVERS = "0<1 0<2 1<3 1<4 2<4 2<7 3<5 3<6 4<9 5<10 6<8 6<9 7<12 8<10 8<11 9<12 10<13 11<13 12<11"
NK = 14
GEN = (1, 3)


def order(n, covers):
    le = [[i == j for j in range(n)] for i in range(n)]
    for c in covers.split():
        a, b = map(int, c.split("<"))
        le[a][b] = True
    for k in range(n):
        for i in range(n):
            for j in range(n):
                if le[i][k] and le[k][j]:
                    le[i][j] = True
    return le


def tables(n, le):
    def lub(a, b):
        ub = [z for z in range(n) if le[a][z] and le[b][z]]
        least = [z for z in ub if all(le[z][w] for w in ub)]
        assert len(least) == 1
        return least[0]

    def glb(a, b):
        lb = [z for z in range(n) if le[z][a] and le[z][b]]
        great = [z for z in lb if all(le[w][z] for w in lb)]
        assert len(great) == 1
        return great[0]

    return [[lub(a, b) for b in range(n)] for a in range(n)], [[glb(a, b) for b in range(n)] for a in range(n)]


def build():
    le = order(NK, K_COVERS)
    ks, ki = tables(NK, le)
    elems = {(x, x) for x in range(NK)} | {GEN}
    while True:
        new = {(ks[a][c], ks[b][d]) for a, b in elems for c, d in elems} | \
              {(ki[a][c], ki[b][d]) for a, b in elems for c, d in elems}
        if new <= elems:
            break
        elems |= new
    P = sorted(elems, key=lambda p: (sum(le[q][p[0]] and le[r][p[1]] for q, r in elems), p))
    idx = {p: i for i, p in enumerate(P)}
    n = len(P)
    sup = [[idx[(ks[a][c], ks[b][d])] for (c, d) in P] for (a, b) in P]
    inf = [[idx[(ki[a][c], ki[b][d])] for (c, d) in P] for (a, b) in P]
    return le, ks, ki, P, idx, n, sup, inf


def name(p):
    a, b = p
    return f"d{a}" if a == b else f"p{a}_{b}"


def derivation(n, sup, inf, base):
    known = list(base)
    steps = []
    while len(known) < n:
        new = None
        for a in known:
            for b in known:
                for op, t in (("sup", sup), ("inf", inf)):
                    if t[a][b] not in known:
                        new = (t[a][b], op, a, b)
                        break
                if new:
                    break
            if new:
                break
        assert new, "the set does not generate the lattice"
        known.append(new[0])
        steps.append(new)
    return steps


def enum_type(w, T, names, doc):
    w(f"/-- {doc} -/")
    w(f"inductive {T} where")
    w("  | " + " | ".join(names))
    w("  deriving DecidableEq")
    w("")
    w(f"namespace {T}")
    w("")
    w(f"instance : Fintype {T} := Fintype.ofList [{', '.join(names)}] (by intro x; cases x <;> simp)")
    w("")


def lattice_tables(w, T, names, sup, inf):
    for op, t in (("sup", sup), ("inf", inf)):
        w(f"/-- the {'join' if op == 'sup' else 'meet'} table -/")
        w(f"def {op} : {T} → {T} → {T}")
        for a in range(len(names)):
            w("  " + " ".join(f"| {names[a]}, {names[b]} => {names[t[a][b]]}" for b in range(len(names))))
        w("")
    w(f"instance : Max {T} := ⟨sup⟩")
    w(f"instance : Min {T} := ⟨inf⟩")
    w("")
    w(f"instance : Lattice {T} :=")
    w("  Lattice.mk' (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel) "
      "(by decide +kernel) (by decide +kernel)")
    w("")
    w(f"instance : DecidableLE {T} := fun a b => inferInstanceAs (Decidable (a ⊔ b = b))")
    w("")
    w(f"/-- `{T}` is join semidistributive. -/")
    w(f"theorem sdSup : ∀ a b c : {T}, a ⊔ b = a ⊔ c → a ⊔ b = a ⊔ (b ⊓ c) := by decide +kernel")
    w("")
    w(f"/-- `{T}` is meet semidistributive. -/")
    w(f"theorem sdInf : ∀ a b c : {T}, a ⊓ b = a ⊓ c → a ⊓ b = a ⊓ (b ⊔ c) := by decide +kernel")
    w("")


def main():
    le, ks, ki, P, idx, n, sup, inf = build()
    assert n == 26
    D = [idx[(x, x)] for x in range(NK)]
    C = [i for i in range(n) if i not in D]
    names = [name(p) for p in P]
    kn = [f"k{i}" for i in range(NK)]
    out = []
    w = out.append
    w("/-")
    w("Generated by scripts/gen_lean.py; do not edit by hand.")
    w("-/")
    w("import Mathlib.Order.Sublattice")
    w("import Mathlib.Order.Atoms")
    w("import Mathlib.Data.Fintype.OfMap")
    w("")
    w("/-!")
    w("# The complement of a maximal sublattice of a finite semidistributive lattice")
    w("")
    w("Adams, Freese, Nation and Schmid (J. Austral. Math. Soc. 63 (1997), Theorem 7) proved that every")
    w("maximal sublattice of a finite bounded lattice `L` has the form `L - [v, u]`, and asked whether this")
    w("extends to finite semidistributive lattices. Adaricheva, Mata, Silberger and Zamojska-Dzienio")
    w("(DMTCS 28:2 (2026)) state the expected answer as a conjecture: the complement of a maximal")
    w("sublattice of a finite semidistributive lattice is an interval.")
    w("")
    w("This file refutes it. `K` is a 14-element semidistributive lattice. `L` is the sublattice of")
    w("`K × K` generated by the diagonal and the pair `(k1, k3)`; it has 26 elements, named `dX` for the")
    w("diagonal pair `(kX, kX)` and `pX_Y` for `(kX, kY)`. The map `emb` identifies `L` with that")
    w("sublattice of `K × K`. The diagonal `D` is a maximal proper sublattice of `L`, and its complement")
    w("has the two minimal elements `p1_3` and `p2_7`, so it is not an interval.")
    w("-/")
    w("")
    w("-- The kernel decides statements over all 26^3 triples of `L`; that needs more than the default budget.")
    w("set_option maxHeartbeats 0")
    w("")
    w("namespace H1")
    w("")
    enum_type(w, "K", kn, "The 14 elements of `K`; `k0` is the least and `k13` the greatest element.")
    lattice_tables(w, "K", kn, ks, ki)
    covs = " ".join(f"`k{c.split('<')[0]} ⋖ k{c.split('<')[1]}`" for c in K_COVERS.split())
    w(f"/-- The covering pairs of `K` are {covs}. -/")
    w("theorem covBy_iff (a b : K) : a ⋖ b ↔ (a < b ∧ ∀ c : K, a < c → ¬c < b) := Iff.rfl")
    w("")
    w("end K")
    w("")
    enum_type(w, "L", names, "The 26 elements of `L`.")
    lattice_tables(w, "L", names, sup, inf)
    w("/-- The embedding of `L` into `K × K`. -/")
    w("def emb : L → K × K")
    w("  " + " ".join(f"| {names[i]} => (K.k{P[i][0]}, K.k{P[i][1]})" for i in range(n)))
    w("")
    w("theorem emb_injective : Function.Injective emb := by")
    w("  have key : ∀ a b : L, emb a = emb b → a = b := by decide +kernel")
    w("  exact fun a b h => key a b h")
    w("")
    w("theorem emb_sup : ∀ a b : L, emb (a ⊔ b) = emb a ⊔ emb b := by decide +kernel")
    w("")
    w("theorem emb_inf : ∀ a b : L, emb (a ⊓ b) = emb a ⊓ emb b := by decide +kernel")
    w("")
    w("/-- Every element of `K` occurs on the diagonal of `L`. -/")
    w("theorem diag_surj : ∀ x : K, ∃ a : L, emb a = (x, x) := by decide +kernel")
    w("")
    w("/-- membership in the diagonal `D` -/")
    w("def inD : L → Bool")
    w("  " + " ".join(f"| {names[i]} => {'true' if i in D else 'false'}" for i in range(n)))
    w("")
    w("theorem inD_iff : ∀ a : L, inD a = true ↔ (emb a).1 = (emb a).2 := by decide +kernel")
    w("")
    w("/-- The diagonal sublattice `D = {(x, x)}` of `L`, a copy of `K`. -/")
    w("def D : Sublattice L where")
    w("  carrier := {x | inD x = true}")
    w("  supClosed' := fun a ha b hb => by")
    w("    have key : ∀ a b : L, inD a = true → inD b = true → inD (a ⊔ b) = true := by decide +kernel")
    w("    exact key a b ha hb")
    w("  infClosed' := fun a ha b hb => by")
    w("    have key : ∀ a b : L, inD a = true → inD b = true → inD (a ⊓ b) = true := by decide +kernel")
    w("    exact key a b ha hb")
    w("")
    w("theorem mem_D (x : L) : x ∈ D ↔ inD x = true := Iff.rfl")
    w("")
    w("/-- The diagonal is a maximal proper sublattice of `L`: a sublattice that contains `D` and one")
    w("more element contains everything. For each element `c` off the diagonal the proof lists the joins")
    w("and meets that generate `L` from `D` and `c`. -/")
    w("theorem isCoatom_D : IsCoatom D := by")
    w("  refine ⟨fun h => ?_, fun S hS => ?_⟩")
    w(f"  · have hc : {names[C[0]]} ∈ D := by simp [h]")
    w("    exact absurd ((mem_D _).1 hc) (by decide +kernel)")
    w("  · obtain ⟨c, hcS, hcD⟩ := SetLike.exists_of_lt hS")
    w("    have hDS : D ≤ S := hS.le")
    for i in D:
        w(f"    have h{i} : {names[i]} ∈ S := hDS ((mem_D _).2 rfl)")
    w("    cases c with")
    for c in range(n):
        if c in D:
            w(f"    | {names[c]} => exact absurd ((mem_D _).2 rfl) hcD")
            continue
        w(f"    | {names[c]} =>")
        w(f"      have h{c} : {names[c]} ∈ S := hcS")
        for (z, op, a, b) in derivation(n, sup, inf, D + [c]):
            lem = "sup_mem" if op == "sup" else "inf_mem"
            w(f"      have h{z} : {names[z]} ∈ S := S.{lem} h{a} h{b}")
        w("      exact eq_top_iff.2 fun x _ => by cases x <;> assumption")
    w("")
    a, b = idx[GEN], idx[(2, 7)]
    w(f"theorem {names[a]}_not_mem : {names[a]} ∉ D := fun h => absurd ((mem_D _).1 h) (by decide +kernel)")
    w("")
    w(f"theorem {names[b]}_not_mem : {names[b]} ∉ D := fun h => absurd ((mem_D _).1 h) (by decide +kernel)")
    w("")
    w(f"/-- The complement of `D` has no least element: `{names[a]}` and `{names[b]}` lie outside `D`, and")
    w(f"every common lower bound of them lies in `D`. -/")
    w("theorem no_least : ¬∃ z : L, z ∉ D ∧ ∀ c : L, c ∉ D → z ≤ c := by")
    w("  rintro ⟨z, hz, h⟩")
    w(f"  have key : ∀ z : L, z ≤ {names[a]} → z ≤ {names[b]} → inD z = true := by decide +kernel")
    w(f"  exact hz (key z (h _ {names[a]}_not_mem) (h _ {names[b]}_not_mem))")
    w("")
    w("/-- The complement of the maximal sublattice `D` is not an interval. -/")
    w("theorem not_interval : ¬∃ u v : L, ∀ x : L, x ∉ D ↔ u ≤ x ∧ x ≤ v := by")
    w("  rintro ⟨u, v, h⟩")
    w("  refine no_least ⟨u, ?_, fun c hc => ((h c).1 hc).1⟩")
    w(f"  have hu := ((h {names[a]}).1 {names[a]}_not_mem)")
    w("  exact (h u).2 ⟨le_rfl, hu.1.trans hu.2⟩")
    w("")
    w("end L")
    w("")
    w("/-- **The question of Adams, Freese, Nation and Schmid has a negative answer**: there is a finite")
    w("semidistributive lattice with a maximal proper sublattice whose complement is not an interval. -/")
    w("theorem not_complement_interval :")
    w("    ¬∀ (α : Type) [Lattice α] [Finite α],")
    w("      (∀ a b c : α, a ⊔ b = a ⊔ c → a ⊔ b = a ⊔ (b ⊓ c)) →")
    w("      (∀ a b c : α, a ⊓ b = a ⊓ c → a ⊓ b = a ⊓ (b ⊔ c)) →")
    w("      ∀ M : Sublattice α, IsCoatom M → ∃ u v : α, ∀ x : α, x ∉ M ↔ u ≤ x ∧ x ≤ v :=")
    w("  fun h => L.not_interval (h L L.sdSup L.sdInf L.D L.isCoatom_D)")
    w("")
    w("end H1")
    os.makedirs("lean/H1", exist_ok=True)
    with open("lean/H1/Counterexample.lean", "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote lean/H1/Counterexample.lean:", n, "elements,", len(C), "off the diagonal")


if __name__ == "__main__":
    main()
